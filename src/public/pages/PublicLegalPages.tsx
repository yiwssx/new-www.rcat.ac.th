function PolicySectionCard({ section }: { section: LegalSection }) {
  return (
    <Card component="section" id={section.id} aria-labelledby={`heading-${section.id}`} variant="outlined">
      <CardContent sx={{ p: { xs: 2.5, md: 3.5 }, "&:last-child": { pb: { xs: 2.5, md: 3.5 } } }}>
        <Typography id={`heading-${section.id}`} component="h2" variant="h5" sx={{ fontWeight: 800, mb: 1.5 }}>
          {section.title}
        </Typography>
        <Stack spacing={1.5}>
          {section.paragraphs?.map((paragraph) => (
            <Typography key={paragraph} variant="body1" sx={{ lineHeight: 1.85, color: "text.secondary" }}>
              {paragraph}
            </Typography>
          ))}
          {section.bullets && (
            <Box component="ul" sx={{ pl: 3, my: 0, color: "text.secondary", "& li + li": { mt: 1.2 } }}>
              {section.bullets.map((bullet) => (
                <Typography key={bullet} component="li" variant="body1" sx={{ lineHeight: 1.8 }}>
                  {bullet}
                </Typography>
              ))}
            </Box>
          )}
        </Stack>
      </CardContent>
    </Card>
  );
}

